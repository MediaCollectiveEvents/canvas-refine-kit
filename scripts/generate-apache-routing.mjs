import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { getCanonicalRoutes, ERROR_SHELL_FILE, SITE_ORIGIN } from "../src/lib/canonicalRoutes.mjs";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const escapePattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function generateApacheRouting(content) {
  const canonicalHost = new URL(SITE_ORIGIN).hostname;
  const apexHost = canonicalHost.replace(/^www\./, "");
  const productionHosts = `^(?:www\\.)?${escapePattern(apexHost)}(?::[0-9]+)?$`;
  const canonicalRules = getCanonicalRoutes(content).map(route => {
    const pattern = route.path === "/" ? "^$" : `^${escapePattern(route.path.slice(1))}/?$`;
    return `RewriteRule ${pattern} /${route.file} [END,NC]`;
  });
  return [
    "# Generated by scripts/generate-apache-routing.mjs from canonicalRoutes.mjs.",
    "# Requires Apache 2.4 mod_rewrite and AllowOverride FileInfo.",
    "",
    "# Retain HTML compression and extend negotiated encoding to built JS/CSS.",
    "<IfModule mod_filter.c>",
    "  <IfModule mod_brotli.c>",
    "    <IfModule mod_deflate.c>",
    "      AddOutputFilterByType BROTLI_COMPRESS;DEFLATE text/html text/css text/javascript application/javascript application/x-javascript",
    "    </IfModule>",
    "    <IfModule !mod_deflate.c>",
    "      AddOutputFilterByType BROTLI_COMPRESS text/html text/css text/javascript application/javascript application/x-javascript",
    "    </IfModule>",
    "  </IfModule>",
    "  <IfModule !mod_brotli.c>",
    "    <IfModule mod_deflate.c>",
    "      AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/x-javascript",
    "    </IfModule>",
    "  </IfModule>",
    "</IfModule>",
    "",
    "<IfModule mod_headers.c>",
    '  <FilesMatch "-[A-Za-z0-9_-]{8,}\\.(?:js|css|png|jpe?g|gif|svg|webp|avif|ico|woff2?|ttf|otf)$">',
    '    Header set Cache-Control "public, max-age=31536000, immutable" "expr=%{REQUEST_URI} =~ m#^/assets/#"',
    "  </FilesMatch>",
    '  Header set Cache-Control "public, max-age=3600, must-revalidate" "expr=%{REQUEST_URI} =~ m#^/uploads/#"',
    '  <FilesMatch "\\.html$">',
    '    Header always set Cache-Control "no-cache"',
    "  </FilesMatch>",
    "</IfModule>",
    "",
    `ErrorDocument 404 /${ERROR_SHELL_FILE}`,
    "RewriteEngine On",
    "RewriteBase /",
    "",
    "# Canonical production hostname and HTTPS before internal route/asset rewrites.",
    "# Excludes staging, localhost and unrelated hosts; query strings are retained.",
    `RewriteCond %{HTTP_HOST} ${productionHosts} [NC]`,
    "RewriteCond %{HTTPS} !=on [OR]",
    `RewriteCond %{HTTP_HOST} !^${escapePattern(canonicalHost)}$ [NC]`,
    "# Use the original encoded path: REQUEST_URI can be decoded in .htaccess.",
    "RewriteCond %{THE_REQUEST} \\s(/[^?\\s]*)",
    `RewriteRule ^ ${SITE_ORIGIN}%1 [R=301,END,NE]`,
    "",
    "# Match Home before the existing-directory bypass. Queries are retained.",
    ...canonicalRules,
    "",
    "# Existing React compatibility redirects and the Decap launcher remain client-side.",
    "RewriteRule ^(?:about|events/calendar|blog(?:/[^/]+)?|manage)/?$ /index.html [END,NC]",
    "",
    "# Leave real assets and directories (including /admin/) to Apache.",
    "RewriteCond %{REQUEST_FILENAME} -f [OR]",
    "RewriteCond %{REQUEST_FILENAME} -d",
    "RewriteRule ^ - [END]",
    "",
    "# A local ErrorDocument preserves both the requested URL and the 404 status.",
    "RewriteRule ^ - [R=404,END]",
    "",
  ].join("\n");
}

export function writeApacheRouting(root = projectRoot, output = "public/.htaccess") {
  const content = JSON.parse(readFileSync(resolve(root, "src/content/events.json"), "utf8"));
  writeFileSync(resolve(root, output), generateApacheRouting(content));
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  writeApacheRouting();
}
